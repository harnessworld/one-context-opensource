"""Project-level generated tool-neutral ``AGENTS.md``.

The generated guide uses these canonical inputs:

* ``knowledge/01_Compiled/one-context/project-overview.md`` — repository
  overview (with a legacy ``knowledge/references/`` fallback).
* ``.onecxt/RULES.md`` — project-wide constraints.
The root artifact is emitted once by the adapt orchestrator and consumed by
Codex, Pi, and other tools that understand ``AGENTS.md``. Tool-native skill
directories carry discovery metadata, so ``AGENTS.md`` does not duplicate a
second routing table.

It is tool-neutral and fully inlined (no per-agent section), so on-demand
agents impose no idle context cost.
"""

from __future__ import annotations

from pathlib import Path

from one_context._knowledge import _is_private_markdown
from one_context.adapters._shared_rules import GENERATED_HEADER_MD
from one_context.adapters._rules_ref import render_rules_block

_OVERVIEW_SRC = "knowledge/01_Compiled/one-context/project-overview.md"
_LEGACY_OVERVIEW_SRC = "knowledge/references/project-overview.md"


def _read_canonical(root: Path, rel_path: str, *, from_first_h2: bool = False) -> str:
    """Read a canonical source, stripping leading HTML-comment lines.

    Internal markers like ``<!-- INTERNAL ... -->`` at the top of the
    source files are not meant for the generated output.  When
    *from_first_h2* is set, also drop everything before the first ``## ``
    heading (used to skip a source's own title + meta-intro paragraph).
    Returns ``""`` when the file is missing.
    """
    path = root / rel_path
    if not path.is_file() or _is_private_markdown(path):
        return ""
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()

    # Drop leading HTML-comment lines and blank lines that precede content.
    start = 0
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("<!--") or stripped == "":
            start = i + 1
            continue
        break
    body = "\n".join(lines[start:]).strip()

    if from_first_h2:
        idx = body.find("\n## ")
        if body.startswith("## "):
            pass  # already starts at an h2
        elif idx != -1:
            body = body[idx + 1 :]
    return body.strip()


def render_overview(root: Path) -> str:
    """Project overview prose, starting at its first ``## `` section."""
    source = (
        _OVERVIEW_SRC
        if (root / _OVERVIEW_SRC).is_file()
        else _LEGACY_OVERVIEW_SRC
    )
    return _read_canonical(root, source, from_first_h2=True)


def build_agents_md(root: Path) -> str:
    """Compose the full tool-neutral ``AGENTS.md`` body (inlined, no @-refs).

    ``AGENTS.md`` is read by tools that do not support ``@file``
    references (Cursor, Codex, OpenCode, Pi), so everything must be inlined.

    Scope: project overview prose + Project Rules references only. The
    skill-*intent* routing table is **deliberately not inlined here** —
    every supported target auto-discovers skills via its own native projection
    (``.claude/skills/``, ``.opencode/skills/``,
    ``.cursor/rules/skill-*.mdc``, ``.hermes/skills/``, or shared
    ``.agents/skills/``), each carrying the full
    ``name``/``description``/``triggers`` frontmatter. A second-hand
    table here would just drift against those stubs.
    """
    sections = [
        GENERATED_HEADER_MD,
        "",
        "# AGENTS.md — AI Tool Usage Guide",
        "",
        "Tool-neutral guidance for AI coding tools (Cursor, Codex, OpenCode, "
        "Pi) working in this repository. Generated by `onecxt adapt` from "
        "the canonical project overview and `.onecxt/RULES.md` — do not edit "
        "by hand. "
        "Skills are auto-discovered per-tool from their respective stub "
        "directories (`.claude/skills/`, `.opencode/skills/`, "
        "`.cursor/rules/skill-*.mdc`, …); no routing table is inlined here.",
        "",
    ]
    overview = render_overview(root)
    if overview:
        sections.extend([overview, ""])
    rules = render_rules_block(root)
    if rules:
        sections.extend([rules])
    return "\n".join(sections).rstrip() + "\n"
