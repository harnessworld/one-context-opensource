def _active_pi_skill_aliases(skills: list) -> set[tuple[str, str]]:
    """Collect ``{(skill_dir, alias)}`` pairs declared in skill frontmatter."""
    active: set[tuple[str, str]] = set()
    for skill in skills:
        aliases = getattr(skill, "frontmatter", {}).get("aliases")
        if not isinstance(aliases, list):
            continue
        for alias_value in aliases:
            alias = str(alias_value).strip()
            if alias:
                active.add((skill.dir_name, alias))
    return active


def _pi_skill_alias_from_content(content: str) -> tuple[str, str] | None:
    """Extract ``(skill_dir, alias)`` from a generated alias prompt body."""
    match = _PI_SKILL_ALIAS_RE.search(content)
    if not match:
        return None
    return (match.group(1), match.group(2))


