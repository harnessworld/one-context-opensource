# Each adapter writes generated skill artifacts to a deterministic location.
# Used by ``_prune_orphan_skill_files`` to reap on-disk files whose source
# skill (under skills/<dir>/SKILL.md) no longer exists, closing a gap where
# deleting a skill left dangling generated files behind. Each entry is
# (base_dir, glob, name_from): ``name_from`` tells how to derive the skill
# dir-name from a matched file path.
_SKILL_GEN_LOCATIONS: tuple[tuple[str, str, str], ...] = (
    (".claude/skills", "*/SKILL.md", "parent"),  # name = grandparent dir
    (".cursor/rules", "skill-*.mdc", "strip_prefix"),  # name = stem minus "skill-"
    (".hermes/skills", "*.md", "stem"),          # name = file stem
    (".opencode/skills", "*/SKILL.md", "parent"),   # name = grandparent dir
    (".agents/skills", "*/SKILL.md", "parent"),   # shared Codex/Pi project skills
)

# Generated per-agent artifacts.  Deleting an agent from meta/agents.yaml must
# not leave a live role or slash prompt behind.  The marker guard in the prune
# helper protects hand-written files in the same directories.
_AGENT_GEN_LOCATIONS: tuple[tuple[str, str, str], ...] = (
    (".claude/agents", "*.md", "stem"),
    (".cursor/rules", "agent-*.mdc", "strip_agent_prefix"),
    (".hermes/agents", "*.md", "stem"),
    (".opencode/agent", "*.md", "stem"),
    (".codex/agents", "*.toml", "stem"),
    (".pi/prompts", "agent-*.md", "strip_agent_prefix"),
)

# Pi short-name slash prompt aliases for opted-in skills (see PiAdapter).
# These live alongside agent prompts in ``.pi/prompts`` but are non-``agent-*``
# files: ``<alias>.md`` whose body carries a ``canonical-source: skills/<dir>/
# SKILL.md; alias: <alias>`` marker.  Pruning derives (skill_dir, alias) from
# that marker, so it is registered separately from the agent/skill tables.
_PI_SKILL_ALIAS_DIR = ".pi/prompts"
_PI_SKILL_ALIAS_RE = re.compile(
    r"canonical-source:\s*skills/([^/]+)/SKILL\.md;\s*alias:\s*([^ >]+)"
)

# Legacy generated locations superseded by newer native layouts. Any file
# here carrying the GENERATED marker is pruned on ``adapt`` so stale
# mirrors (e.g. the old ``.codex/agent/*.md`` doc forms) don't linger
# alongside their native replacements.
_LEGACY_GEN_LOCATIONS: tuple[tuple[str, str], ...] = (
    (".codex/agent", "*.md"),   # superseded by .codex/agents/<id>.toml
    (".codex/skills", "*/SKILL.md"),  # superseded by shared .agents/skills
    (".openclaw/agents", "*.json"),  # OpenClaw ignores project-local agents
    (".openclaw/skills", "*.json"),  # OpenClaw ignores project-local skills
)

# Adapters that stay registered for tests / ``--only``, but are not written
# by default ``adapt``. Cursor alwaysApply skill shells inflate every chat.
_DEFAULT_SKIP_ADAPTERS = frozenset({"cursor"})
_SKIPPED_ADAPTER_SURFACES: dict[str, tuple[tuple[str, str], ...]] = {
    "cursor": ((".cursor/rules", "*.mdc"),),
}


def _adapter_names_for_run(
    available_adapters: list[str], only: str | None
) -> list[str]:
    """Return adapters to run. Default skips ``_DEFAULT_SKIP_ADAPTERS``."""
    if only:
        return [only]
    return [name for name in available_adapters if name not in _DEFAULT_SKIP_ADAPTERS]


def _prune_skipped_adapter_files(
    root: Path, adapter_names: list[str], dry_run: bool
) -> list[str]:
    """Delete generated files for adapters that this run did not emit."""
    from one_context.adapters._shared_rules import is_generated_content

    removed: list[str] = []
    active = set(adapter_names)
    for name, surfaces in _SKIPPED_ADAPTER_SURFACES.items():
        if name in active:
            continue
        for base_rel, pattern in surfaces:
            base = root / base_rel
            if not base.is_dir() or not _is_safe_owned_path(root, base):
                continue
            for target in sorted(base.glob(pattern)):
                if not target.is_file() or not _is_safe_prune_target(root, base, target):
                    continue
                try:
                    content = target.read_text(encoding="utf-8")
                except OSError:
                    continue
                if not is_generated_content(content):
                    continue
                rel = target.relative_to(root).as_posix()
                removed.append(rel)
                if not dry_run:
                    target.unlink()
            if not dry_run:
                try:
                    base.rmdir()
                except OSError:
                    pass
                parent = base.parent
                if parent != root and parent.is_dir():
                    try:
                        parent.rmdir()
                    except OSError:
                        pass
    return removed


def _evict_skipped_adapter_cache_entries(
    cache: dict[str, str], adapter_names: list[str], dry_run: bool
) -> list[str]:
    """Drop cache keys for skipped adapter surfaces."""
    if dry_run:
        return []
    active = set(adapter_names)
    prefixes: list[str] = []
    for name, surfaces in _SKIPPED_ADAPTER_SURFACES.items():
        if name in active:
            continue
        prefixes.extend(f"{base_rel}/" for base_rel, _ in surfaces)
    evicted = [
        rel_path
        for rel_path in sorted(cache)
        if any(rel_path.startswith(prefix) for prefix in prefixes)
    ]
    for rel_path in evicted:
        del cache[rel_path]
    return evicted


def _is_safe_owned_path(root: Path, path: Path) -> bool:
    """Return whether *path* stays inside root without crossing a symlink."""
    try:
        relative_path = path.relative_to(root)
        lexical = root
        for part in relative_path.parts:
            lexical /= part
            if lexical.is_symlink():
                return False
        path.resolve().relative_to(root.resolve())
    except (OSError, RuntimeError, ValueError):
        return False
    return True


def _is_safe_prune_target(root: Path, base: Path, target: Path) -> bool:
    """Reject symlinks and candidates that resolve outside their owned tree."""
    if not _is_safe_owned_path(root, base) or not _is_safe_owned_path(root, target):
        return False
    try:
        target.relative_to(base)
        base_resolved = base.resolve()
        target_resolved = target.resolve()
        target_resolved.relative_to(base_resolved)
    except (OSError, RuntimeError, ValueError):
        return False
    return True


def _classify_legacy_gen_files(
    root: Path,
    cache: dict[str, str],
) -> tuple[list[str], list[str]]:
    """Return ``(managed, blocked)`` retired paths without changing disk."""
    from one_context.adapters._shared_rules import is_generated_content
    from one_context.cache import file_hash

    managed: list[str] = []
    blocked: list[str] = []
    for base_rel, pattern in _LEGACY_GEN_LOCATIONS:
        base = root / base_rel
        if not base.exists() and not base.is_symlink():
            continue
        if not base.is_dir() or not _is_safe_owned_path(root, base):
            blocked.append(Path(base_rel).as_posix())
            continue
        for target in sorted(base.glob(pattern)):
            rel = target.relative_to(root).as_posix()
            if not target.is_file() or not _is_safe_prune_target(root, base, target):
                blocked.append(rel)
                continue
            try:
                content = target.read_text(encoding="utf-8")
            except OSError:
                blocked.append(rel)
                continue
            if (
                is_generated_content(content)
                and cache.get(rel) == file_hash(content)
            ):
                managed.append(rel)
            else:
                blocked.append(rel)
    return sorted(set(managed)), sorted(set(blocked))


def _prune_legacy_gen_files(
    root: Path,
    dry_run: bool,
    cache: dict[str, str] | None = None,
) -> list[str]:
    """Delete only retired files proven unchanged since onecxt generated them."""
    managed, _ = _classify_legacy_gen_files(root, cache or {})
    for rel in managed:
        if not dry_run:
            (root / rel).unlink()
    if not dry_run:
        for base_rel, _ in _LEGACY_GEN_LOCATIONS:
            base = root / base_rel
            if not base.is_dir() or not _is_safe_owned_path(root, base):
                continue
            # Remove only empty directories within the retired tree.
            for candidate in sorted(
                (
                    path
                    for path in base.glob("*")
                    if path.is_dir() and _is_safe_owned_path(root, path)
                ),
                reverse=True,
            ):
                try:
                    candidate.rmdir()
                except OSError:
                    pass
            try:
                base.rmdir()
            except OSError:
                pass
    return managed


def _legacy_gen_blockers(root: Path, cache: dict[str, str]) -> list[str]:
    """Return retired files that are hand-written or differ from cached output."""
    _, blocked = _classify_legacy_gen_files(root, cache)
    return blocked


def _is_legacy_cache_path(rel_path: str) -> bool:
    path = Path(rel_path)
    for base_rel, pattern in _LEGACY_GEN_LOCATIONS:
        try:
            nested_path = path.relative_to(Path(base_rel))
        except ValueError:
            continue
        if (
            len(nested_path.parts) == len(Path(pattern).parts)
            and nested_path.match(pattern)
        ):
            return True
    return False


def _evict_legacy_cache_entries(
    root: Path,
    cache: dict[str, str],
    removed_paths: set[str],
    dry_run: bool,
) -> list[str]:
    """Evict retired cache keys only after deletion or when disk is absent."""
    if dry_run:
        return []
    evicted = [
        rel_path
        for rel_path in sorted(cache)
        if _is_legacy_cache_path(rel_path)
        and (rel_path in removed_paths or not (root / rel_path).exists())
    ]
    for rel_path in evicted:
        del cache[rel_path]
    return evicted


def _prune_orphan_skill_files(
    root: Path, active_skill_dirs: set[str], dry_run: bool
) -> list[str]:
    """Delete generated skill files whose source skill no longer exists.

    Only files whose content carries the onecxt ``GENERATED`` marker are
    removed, so hand-written files in the same directories are never touched.
    Empty ``.claude/skills/<name>/`` directories left behind are removed too.

    Returns the list of removed (or would-be-removed, in dry-run) paths.
    """
    from one_context.adapters._shared_rules import is_generated_content

    removed: list[str] = []
    for base_rel, pattern, name_from in _SKILL_GEN_LOCATIONS:
        base = root / base_rel
        if not base.is_dir() or not _is_safe_owned_path(root, base):
            continue
        for target in sorted(base.glob(pattern)):
            if not target.is_file() or not _is_safe_prune_target(root, base, target):
                continue
            stem = target.stem
            if name_from == "parent":
                skill_name = target.parent.name
            elif name_from == "strip_prefix":
                skill_name = stem[len("skill-"):] if stem.startswith("skill-") else stem
            else:  # "stem"
                skill_name = stem
            if skill_name in active_skill_dirs:
                continue
            try:
                content = target.read_text(encoding="utf-8")
            except OSError:
                continue
            if not is_generated_content(content):
                continue  # never touch hand-written files
            rel = target.relative_to(root).as_posix()
            removed.append(rel)
            if not dry_run:
                target.unlink()
                # Drop the now-empty per-skill dir for the .claude/skills case.
                parent = target.parent
                if name_from == "parent" and parent.is_dir() and not any(parent.iterdir()):
                    try:
                        parent.rmdir()
                    except OSError:
                        pass
    return removed


