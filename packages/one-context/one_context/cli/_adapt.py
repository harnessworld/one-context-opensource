def _print_dry_run_block(rel_path: str, description: str, body: str) -> None:
    """Print generated content in dry-run mode.

    On Windows, ``sys.stdout`` may use a legacy encoding (e.g. GBK) that
    cannot encode some UTF-8 characters from knowledge files; fall back to
    writing UTF-8 bytes so ``--dry-run`` does not crash.
    """
    block = f"--- {rel_path} ({description}) ---\n{body}\n"
    try:
        sys.stdout.write(block)
    except UnicodeEncodeError:
        sys.stdout.buffer.write(block.encode("utf-8", errors="replace"))


def _detect_user_edited(root: Path, rel_path: str, existing: str) -> bool:
    """Return True if *existing* content does NOT belong to onecxt.

    Two-phase detection:
    1. Marker check (fast path for .md files): hand-written files in
       ``skills/``, ``agent/``, ``instructions/`` directories ship an inline
       ``<!-- GENERATED by onecxt adapt -->`` marker; absence ⇒ USER_EDITED.
    2. Ownership check (for JSON files that reject inline markers): accept
       only an exact on-disk hash from ``.onecxt/adapt-cache.json``.

    For files silently introduced between versions (no marker, matching cache,
    or cache entry), we err on the side of caution and treat them as
    USER_EDITED — ``--force`` is the explicit override. A report records what
    happened during a run; its path alone is never proof that the current
    bytes still belong to onecxt.
    """
    from one_context.adapters._shared_rules import is_generated_content

    if is_generated_content(existing):
        return False

    # A matching cache entry remains valid even when a later ``--only`` run
    # replaces adapt-report.json with another adapter's entries.
    try:
        from one_context.cache import file_hash, load_cache

        if load_cache(root).get(rel_path) == file_hash(existing):
            return False
    except (OSError, ValueError):
        pass

    return True


def _emit_file(
    root: Path,
    gf,
    dry_run: bool,
    cache: dict[str, str] | None = None,
    force: bool = False,
) -> tuple[bool, str]:
    """Write a generated file to disk, or print in dry-run mode.

    Returns ``(did_write, file_status)`` where ``file_status`` is one of the
    ``adapters._report.FILE_*`` constants. The status feeds into
    ``adapt-report.json``.

    USER_EDITED protection: if the on-disk file has neither the generated
    marker nor cache/report proof of onecxt ownership, skip the overwrite
    (unless *force*) and report ``skipped_user_edited``. Files that DO carry
    the marker but differ in content are treated as STALE generator output.
    """
    target = root / gf.rel_path
    existing: str | None = None

    if target.is_file():
        existing = target.read_text(encoding="utf-8")
        if _detect_user_edited(root, gf.rel_path, existing) and not force:
            # User hand-edited a file we generated previously — refuse to clobber
            # unless --force. Report and skip.
            if dry_run:
                _print_dry_run_block(
                    gf.rel_path,
                    "USER_EDITED (would skip without --force)",
                    gf.content,
                )
                return False, "skipped_user_edited"
            print(
                f"skip: {gf.rel_path} (USER_EDITED — hand-edited; use --force to overwrite)",
                file=sys.stderr,
            )
            return False, "skipped_user_edited"

    if cache is not None and not dry_run and not force:
        from one_context.cache import needs_write

        if (
            existing == gf.content
            and not needs_write(gf.rel_path, gf.content, cache)
        ):
            return False, "cached"

    if dry_run:
        _print_dry_run_block(gf.rel_path, gf.description, gf.content)
        return True, "dry_run"

    parent = target.parent
    if parent.is_symlink():
        parent.unlink()
    parent.mkdir(parents=True, exist_ok=True)
    target.write_text(gf.content, encoding="utf-8")
    print(f"wrote: {gf.rel_path} ({gf.description})")
    if cache is not None:
        from one_context.cache import update_cache
        update_cache(gf.rel_path, gf.content, cache)
    return True, "written"


def _check_generated(
    root: Path,
    files: list,
    *,
    orphan_paths: list[str] | None = None,
    blocked_paths: list[str] | None = None,
) -> int:
    """Compare generated content to disk. Return 0 if all match, 1 if any differ.

    Distinguishes three failure modes per file:
    * ``missing``      — target file doesn't exist
    * ``stale``        — exists with marker but generated content differs
    * ``user_edited``  — exists without marker or matching cached hash
    """
    missing: list[str] = []
    stale: list[str] = []
    user_edited: list[str] = []

    for gf in files:
        target = root / gf.rel_path
        if not target.is_file():
            missing.append(f"  missing: {gf.rel_path}")
            continue
        existing = target.read_text(encoding="utf-8")
        if _detect_user_edited(root, gf.rel_path, existing):
            user_edited.append(f"  user_edited: {gf.rel_path}")
            continue
        if existing != gf.content:
            stale.append(f"  stale:   {gf.rel_path}")

    orphans = [f"  orphan:  {path}" for path in (orphan_paths or [])]
    blockers = [f"  blocked: {path}" for path in (blocked_paths or [])]

    if not (missing or stale or user_edited or orphans or blockers):
        print("adapt --check: all generated files are up-to-date.")
        return 0

    print("adapt --check: generated files are NOT up-to-date:", file=sys.stderr)
    for line in missing + stale + user_edited + orphans + blockers:
        print(line, file=sys.stderr)
    print(
        "\nRun `onecxt adapt --all` to regenerate (add --force to overwrite "
        "USER_EDITED files).",
        file=sys.stderr,
    )
    return 1


def _duplicate_generated_paths(files: list) -> list[str]:
    """Return generated paths with more than one producer."""
    counts = Counter(gf.rel_path for gf in files if gf.rel_path)
    return sorted(path for path, count in counts.items() if count > 1)


def _unsafe_generated_paths(root: Path, files: list) -> list[str]:
    """Return output paths that are absolute, traversal-based, or escape root."""
    root_resolved = root.resolve()
    unsafe: list[str] = []
    for gf in files:
        rel_path = Path(gf.rel_path)
        if (
            not gf.rel_path
            or rel_path.is_absolute()
            or ".." in rel_path.parts
        ):
            unsafe.append(gf.rel_path)
            continue
        try:
            lexical = root
            for part in rel_path.parts:
                lexical /= part
                if lexical.is_symlink():
                    raise ValueError("generated path crosses a symlink")
            (root / rel_path).resolve().relative_to(root_resolved)
        except (OSError, RuntimeError, ValueError):
            unsafe.append(gf.rel_path)
    return sorted(set(unsafe))


def _report_dirty_files(root: Path, files: list) -> None:
    """Detect and report files that were modified externally since last adapt.

    Same as before for verbose output; USER_EDITED detection is now done in
    ``_emit_file`` so the warning no longer fires for files that will be
    skipped (would be misleading). Only report files we WILL overwrite.
    """
    dirty_count = 0
    for gf in files:
        target = root / gf.rel_path
        if not target.is_file():
            continue
        existing = target.read_text(encoding="utf-8")
        # Skip USER_EDITED files — _emit_file will refuse them
        if _detect_user_edited(root, gf.rel_path, existing):
            continue
        if existing != gf.content:
            dirty_count += 1
            diff_lines = list(difflib.unified_diff(
                existing.splitlines(keepends=True),
                gf.content.splitlines(keepends=True),
                fromfile=f"disk:{gf.rel_path}",
                tofile=f"generated:{gf.rel_path}",
                n=1,
            ))
            add_count = sum(
                1
                for line in diff_lines
                if line.startswith("+") and not line.startswith("+++")
            )
            del_count = sum(
                1
                for line in diff_lines
                if line.startswith("-") and not line.startswith("---")
            )
            print(f"  dirty: {gf.rel_path} (+{add_count}/-{del_count} lines)")

    if dirty_count:
        print(f"warning: {dirty_count} generated file(s) differ from expected output; overwriting.")


