# ---------------------------------------------------------------------------
# Generated-file marker
# ---------------------------------------------------------------------------

GENERATED_MARKER = "GENERATED by onecxt adapt"

GENERATED_HEADER_MD = (
    f"<!-- {GENERATED_MARKER} — DO NOT EDIT. "
    "Changes will be overwritten. Edit the sources instead: "
    ".onecxt/RULES.md (rules), meta/*.yaml (workspaces/profiles/agents), "
    "skills/ (skills). -->"
)

GENERATED_NOTICE_JSON = (
    f"{GENERATED_MARKER} — DO NOT EDIT. "
    "Changes will be overwritten. Edit the sources instead: "
    ".onecxt/RULES.md (rules), meta/*.yaml (workspaces/profiles/agents), "
    "skills/ (skills)."
)


def is_generated_content(content: str) -> bool:
    """Return True if *content* carries the onecxt generated marker.

    Detects the Markdown comment form (``GENERATED by onecxt adapt``) in
    ``.md`` files. For JSON-manifest files (opencode.json, openclaw *.json),
    OpenCode rejects unknown top-level keys, so we cannot stamp an inline
    marker; USER_EDITED detection for JSON relies on the previous
    ``adapt-report.json`` tracking the file as generated.
    """
    if GENERATED_MARKER in content:
        return True
    # OpenClaw legacy marker field carries the marker string in text — caught above
    return False


